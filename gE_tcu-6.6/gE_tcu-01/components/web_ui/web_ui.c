static esp_err_t set_time_handler(httpd_req_t *req) {
    char buf[256], ts[32], tzoff[16], tzname[32];
    if (httpd_req_get_url_query_str(req, buf, sizeof(buf)) == ESP_OK) {
        if (httpd_query_key_value(buf, "ts", ts, sizeof(ts)) == ESP_OK) {
            time_t t_utc = (time_t)atoll(ts);
            
            if (httpd_query_key_value(buf, "tzOffset", tzoff, sizeof(tzoff)) == ESP_OK) {
                float offset = -atof(tzoff) / 60.0f;
                if (httpd_query_key_value(buf, "tzName", tzname, sizeof(tzname)) == ESP_OK) {
                    solar_math_set_timezone(offset, tzname);
                } else {
                    solar_math_set_timezone(offset, "UTC");
                }
            }
            
            hal_set_time(t_utc);
            ESP_LOGI(TAG, "Syncing time: Raw UTC Timestamp: %lld", (long long)t_utc);
            httpd_resp_send(req, "Time Set Success.", HTTPD_RESP_USE_STRLEN);
#if defined(HACK_TIME_SET_WIFI_OFF)
            xTaskCreate(stop_wifi_task, "stop_wifi", 2048, NULL, 5, NULL);
#elif defined(HACK_AP_AGAIN_AFTER_SYNC)
            wifi_switch_to_ap_mode();
#endif
            return ESP_OK;
        }
    }
    httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "Invalid params");
    return ESP_OK;
}

static esp_err_t wifi_scan_handler(httpd_req_t *req) {
    wifi_scan_config_t scan_config = {0};
    esp_wifi_scan_start(&scan_config, true);
    
    uint16_t ap_count = 0;
    esp_wifi_scan_get_ap_num(&ap_count);
    if (ap_count > 20) ap_count = 20;
    
    wifi_ap_record_t *ap_info = malloc(sizeof(wifi_ap_record_t) * ap_count);
    if (!ap_info) return ESP_FAIL;
    esp_wifi_scan_get_ap_records(&ap_count, ap_info);
    
    char *json = malloc(4096);
    if (!json) { free(ap_info); return ESP_FAIL; }
    
    int pos = snprintf(json, 4096, "[");
    for (int i = 0; i < ap_count; i++) {
        int written = snprintf(json + pos, 4096 - pos, "{\"ssid\":\"%s\",\"rssi\":%d}%s", 
                               (char*)ap_info[i].ssid, ap_info[i].rssi, (i < ap_count - 1) ? "," : "");
        if (written > 0) pos += written;
    }
    snprintf(json + pos, 4096 - pos, "]");
    
    free(ap_info);
    httpd_resp_set_type(req, "application/json");
    httpd_resp_send(req, json, HTTPD_RESP_USE_STRLEN);
    free(json);
    return ESP_OK;
}

static esp_err_t wifi_connect_handler(httpd_req_t *req) {
    char buf[128], ssid[64], pass[64];
    if (httpd_req_get_url_query_str(req, buf, sizeof(buf)) == ESP_OK &&
        httpd_query_key_value(buf, "ssid", ssid, sizeof(ssid)) == ESP_OK &&
        httpd_query_key_value(buf, "pass", pass, sizeof(pass)) == ESP_OK) {
        
        nvs_handle_t my_handle;
        if (nvs_open("wifi-creds", NVS_READWRITE, &my_handle) == ESP_OK) {
            nvs_set_str(my_handle, "ssid", ssid);
            nvs_set_str(my_handle, "pass", pass);
            nvs_commit(my_handle);
            nvs_close(my_handle);
        }
        httpd_resp_send(req, "Credentials saved. Reconnecting...", HTTPD_RESP_USE_STRLEN);
        vTaskDelay(pdMS_TO_TICKS(500));
        esp_restart();
    }
    httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "Missing parameters");
    return ESP_OK;
}

static esp_err_t wifi_logout_handler(httpd_req_t *req) {
    nvs_handle_t my_handle;
    if (nvs_open("wifi-creds", NVS_READWRITE, &my_handle) == ESP_OK) {
        nvs_erase_all(my_handle);
        nvs_commit(my_handle);
        nvs_close(my_handle);
    }
    httpd_resp_send(req, "WiFi Forgotten. Restarting to AP mode...", HTTPD_RESP_USE_STRLEN);
    vTaskDelay(pdMS_TO_TICKS(500));
    esp_restart();
    return ESP_OK;
}


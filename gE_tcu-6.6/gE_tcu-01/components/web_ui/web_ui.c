static esp_err_t status_handler(httpd_req_t *req) {
    web_note_activity();
    time_t t = hal_get_time();
    
    cJSON *root = tracker_get_status_json(tracker);
    if (!root) return ESP_FAIL;
    
    // Explicitly update 'time' field in JSON with hal_get_time() to ensure RTC sync is reflected
    cJSON_ReplaceItemInObject(root, "time", cJSON_CreateNumber((double)t));
    cJSON_AddNumberToObject(root, "interval_min", TRACKER_INTERVAL_MINUTES);

    struct tm dt_utc;
    gmtime_r(&t, &dt_utc);
    char utc_buf[64];
    snprintf(utc_buf, sizeof(utc_buf), "%04d-%02d-%02d %02d:%02d:%02d", 
             dt_utc.tm_year + 1900, dt_utc.tm_mon + 1, dt_utc.tm_mday, 
             dt_utc.tm_hour, dt_utc.tm_min, dt_utc.tm_sec);

    // Explicitly ensure time_str and other essential UI fields are present
    cJSON_AddStringToObject(root, "time_str", utc_buf);
    /* Anemometer: wind_ok=false when the sensor is offline (UI shows ---) */
    float wind_speed = 0.0f;
    bool wind_ok = anemometer_get(&wind_speed);
    cJSON_AddNumberToObject(root, "wind_speed", wind_ok ? (double)wind_speed : 0.0);
    cJSON_AddBoolToObject(root, "wind_ok", wind_ok);
    cJSON_AddBoolToObject(root, "motor_up", hal_is_motor_moving_up());
    cJSON_AddBoolToObject(root, "motor_down", hal_is_motor_moving_down());
    cJSON_AddBoolToObject(root, "up_btn", hal_is_up_button_pressed());
    cJSON_AddBoolToObject(root, "down_btn", hal_is_down_button_pressed());

    // Fallback for tz_name if missing
    if (!cJSON_GetObjectItem(root, "tz_name") || cJSON_IsNull(cJSON_GetObjectItem(root, "tz_name"))) {
        cJSON_AddStringToObject(root, "tz_name", "UTC");
    }

    char sntp_diag[64];
#ifdef USE_SNTP
    sntp_sync_status_t status = esp_sntp_get_sync_status();
    const char* status_str = (status == SNTP_SYNC_STATUS_COMPLETED) ? "SYNCED" : "RESET";
    snprintf(sntp_diag, sizeof(sntp_diag), "SNTP:%s", status_str);
#else
    snprintf(sntp_diag, sizeof(sntp_diag), "SNTP:DISABLED");
#endif

    const cJSON *diag_item = cJSON_GetObjectItem(root, "diagnostics");
    const char *diag_str = (diag_item && cJSON_IsString(diag_item) && diag_item->valuestring) ? diag_item->valuestring : "";
    char diag_combined[192];
    if (diag_str[0] != '\0') {
        snprintf(diag_combined, sizeof(diag_combined), "%s | %s", diag_str, sntp_diag);
    } else {
        snprintf(diag_combined, sizeof(diag_combined), "%s", sntp_diag);
    }
    cJSON_ReplaceItemInObject(root, "diagnostics", cJSON_CreateString(diag_combined));

    char *json_str = cJSON_PrintUnformatted(root);
    if (!json_str) {
        cJSON_Delete(root);
        return ESP_FAIL;
    }
    httpd_resp_set_type(req, "application/json");
    httpd_resp_send(req, json_str, HTTPD_RESP_USE_STRLEN);
    
    free(json_str);
    cJSON_Delete(root);
    return ESP_OK;
}


#ifdef USE_SNTP
static void sntp_monitor_task(void* arg) {
    ESP_LOGI(TAG, "SNTP Monitor: Waiting for sync (max 30s)...");
    esp_err_t ret = esp_netif_sntp_sync_wait(pdMS_TO_TICKS(30000));
    if (ret == ESP_OK) {
        ESP_LOGI(TAG, "SNTP Sync Status: COMPLETED via wait");
    } else {
        ESP_LOGW(TAG, "SNTP Sync Status: TIMEOUT or ERROR (%s)", esp_err_to_name(ret));
    }
    vTaskDelete(NULL);
}

static void time_sync_notification_cb(struct timeval *tv) {
    ESP_LOGI(TAG, "SNTP Sync Success callback triggered. Updating RTC...");
    hal_set_time(tv->tv_sec);
#if defined(HACK_TIME_SET_WIFI_OFF)
    xTaskCreate(stop_wifi_task, "stop_wifi", 2048, NULL, 5, NULL);
#elif defined(HACK_AP_AGAIN_AFTER_SYNC)
    wifi_switch_to_ap_mode();
#endif
}

static void initialize_sntp(void) {
    ESP_LOGI(TAG, "Initializing SNTP using NPL India servers (match demo project)...");
    esp_sntp_config_t config = ESP_NETIF_SNTP_DEFAULT_CONFIG("time.nplindia.org");
    config.sync_cb = time_sync_notification_cb;
    
    esp_netif_sntp_deinit();
    esp_err_t ret = esp_netif_sntp_init(&config);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "Failed to init SNTP: %s", esp_err_to_name(ret));
        return;
    }
    xTaskCreate(sntp_monitor_task, "sntp_monitor", 2048, NULL, 5, NULL);
}
#endif

static void wifi_event_handler(void* arg, esp_event_base_t event_base, int32_t event_id, void* event_data) {
    if (event_base == WIFI_EVENT && event_id == WIFI_EVENT_STA_START) {
        esp_wifi_connect();
    } else if (event_base == WIFI_EVENT && event_id == WIFI_EVENT_STA_DISCONNECTED) {
        if (s_wifi_intentional_ap_only) {
            ESP_LOGI(TAG, "STA disconnected intentionally — staying in AP-only mode.");
            return;
        }
        ESP_LOGI(TAG, "STA Disconnected. Re-enabling AP for configuration...");
        esp_wifi_set_mode(WIFI_MODE_APSTA);
        esp_wifi_connect();
    } else if (event_base == IP_EVENT && event_id == IP_EVENT_STA_GOT_IP) {
        xEventGroupSetBits(s_wifi_event_group, WIFI_CONNECTED_BIT);
        
        ESP_LOGI(TAG, "STA Connected (IP obtained). Keeping AP active in APSTA mode.");
        // esp_wifi_set_mode(WIFI_MODE_STA); // Removed to keep AP active

#ifdef USE_SNTP
        // Give the network stack a moment to breathe (match demo project)
        vTaskDelay(pdMS_TO_TICKS(1000));
        initialize_sntp();
#endif
    }
}

static void wifi_init_ap_sta(void) {
    s_wifi_event_group = xEventGroupCreate();
    ESP_ERROR_CHECK(esp_netif_init());
    /* The Ethernet bring-up (eth_w5500_start) may already have created the default event loop;
     * that is fine - only a real failure is fatal. */
    esp_err_t loop_err = esp_event_loop_create_default();
    if (loop_err != ESP_OK && loop_err != ESP_ERR_INVALID_STATE) ESP_ERROR_CHECK(loop_err);

    esp_netif_create_default_wifi_sta();
    esp_netif_create_default_wifi_ap();

    wifi_init_config_t cfg = WIFI_INIT_CONFIG_DEFAULT();
    ESP_ERROR_CHECK(esp_wifi_init(&cfg));

    esp_event_handler_instance_register(WIFI_EVENT, ESP_EVENT_ANY_ID, &wifi_event_handler, NULL, NULL);
    esp_event_handler_instance_register(IP_EVENT, IP_EVENT_STA_GOT_IP, &wifi_event_handler, NULL, NULL);

    nvs_handle_t my_handle;
    char ssid[32] = {0};
    char pass[64] = {0};
    size_t required_size;
    bool has_creds = false;

    if (nvs_open("wifi-creds", NVS_READONLY, &my_handle) == ESP_OK) {
        required_size = sizeof(ssid);
        if (nvs_get_str(my_handle, "ssid", ssid, &required_size) == ESP_OK) {
            required_size = sizeof(pass);
            nvs_get_str(my_handle, "pass", pass, &required_size);
            has_creds = true;
        }
        nvs_close(my_handle);
    }

    wifi_config_t wifi_sta_config = {0};
    if (has_creds) {
        strncpy((char *)wifi_sta_config.sta.ssid, ssid, sizeof(wifi_sta_config.sta.ssid));
        strncpy((char *)wifi_sta_config.sta.password, pass, sizeof(wifi_sta_config.sta.password));
    }

    wifi_config_t wifi_ap_config = {
        .ap = {
            .ssid = "Glarenergy-TCU",
            .ssid_len = strlen("Glarenergy-TCU"),
            .password = "glarenergy",
            .max_connection = 4,
            .authmode = WIFI_AUTH_WPA2_PSK
        },
    };

    if (has_creds) {
        ESP_ERROR_CHECK(esp_wifi_set_mode(WIFI_MODE_APSTA));
        ESP_ERROR_CHECK(esp_wifi_set_config(WIFI_IF_STA, &wifi_sta_config));
    } else {
        ESP_ERROR_CHECK(esp_wifi_set_mode(WIFI_MODE_AP));
        s_wifi_intentional_ap_only = true;
    }
    ESP_ERROR_CHECK(esp_wifi_set_config(WIFI_IF_AP, &wifi_ap_config));
    ESP_ERROR_CHECK(esp_wifi_start());
    s_wifi_initialized = true;

    mdns_init();
    mdns_hostname_set("glarenergy");
    mdns_instance_name_set("Glarenergy TCU");
    mdns_service_add(NULL, "_http", "_tcp", 80, NULL, 0);
    mdns_service_txt_item_set("_http", "_tcp", "path", "/");
}


/* Called once from app_main after NVS, HAL and tracker are initialised. */
void web_ui_start(void) {
    esp_vfs_spiffs_conf_t conf = {
        .base_path = "/storage",
        .partition_label = "storage",
        .max_files = 5,
        .format_if_mount_failed = true
    };
    esp_err_t ret = esp_vfs_spiffs_register(&conf);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "SPIFFS mount failed (%s)", esp_err_to_name(ret));
    } else {
        size_t total = 0, used = 0;
        esp_spiffs_info("storage", &total, &used);
        ESP_LOGI(TAG, "SPIFFS total: %u, used: %u", (unsigned)total, (unsigned)used);
    }

    bool should_start_wifi = true;
#ifdef HACK_TIME_SET_WIFI_OFF
    if (hal_rtc_is_valid()) {
        should_start_wifi = false;
        ESP_LOGI(TAG, "RTC valid and HACK_TIME_SET_WIFI_OFF enabled. Skipping WiFi/Server.");
    }
#endif
    if (should_start_wifi) {
        ESP_LOGI(TAG, "Starting WiFi and Server...");
        wifi_init_ap_sta();
        start_webserver();
    }
}

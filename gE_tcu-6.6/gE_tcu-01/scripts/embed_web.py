#!/usr/bin/env python3
"""Turn the web UI files into C arrays (components/web_ui/web_assets_gen.c/.h).

Replaces ESP-IDF's EMBED_FILES, which breaks under PlatformIO ("index.html.S not found").
Re-run after editing any web file:   python scripts/embed_web.py [web_dir]
web_dir defaults to components/web_ui/web_assets if it exists, else web/
"""
import os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
comp = os.path.join(root, "components", "web_ui")
default = os.path.join(comp, "web_assets")
if not os.path.isdir(default):
    default = os.path.join(root, "web")
web = sys.argv[1] if len(sys.argv) > 1 else default

FILES = ["index.html", "style.css", "dist/app.min.js", "dist/bulma.min.css", "dist/oss_licenses.txt"]

def ident(rel):
    return "web_" + re.sub(r"[^0-9a-zA-Z]", "_", os.path.basename(rel))

with open(os.path.join(comp, "web_assets_gen.c"), "w") as c, \
     open(os.path.join(comp, "web_assets_gen.h"), "w") as h:
    c.write("/* Generated by scripts/embed_web.py - DO NOT EDIT */\n#include \"web_assets_gen.h\"\n\n")
    h.write("/* Generated by scripts/embed_web.py - DO NOT EDIT */\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n")
    for rel in FILES:
        data = open(os.path.join(web, rel), "rb").read()
        n = ident(rel)
        h.write(f"extern const uint8_t {n}[];\nextern const size_t  {n}_len;\n")
        c.write(f"const size_t {n}_len = {len(data)};\nconst uint8_t {n}[] = {{\n")
        for i in range(0, len(data), 24):
            c.write(",".join(str(b) for b in data[i:i+24]) + ",\n")
        c.write("0};\n\n")          # trailing NUL, not counted in _len
        print(f"{rel}: {len(data)} bytes -> {n}")

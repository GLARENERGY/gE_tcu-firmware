import yaml
import os
import sys

def parse_value(val):
    """Convert string values to appropriate Python types."""
    if val.lower() == 'true': return True
    if val.lower() == 'false': return False
    try:
        if '.' in val: return float(val)
        return int(val)
    except ValueError:
        return val

def generate_config(config_path, output_path, overrides=None):
    if overrides is None:
        overrides = {}

    if not os.path.exists(config_path):
        print(f"Error: {config_path} not found")
        return

    with open(config_path, 'r') as f:
        config = yaml.safe_load(f) or {}

    # Apply overrides to the nested structure
    for key, val in overrides.items():
        found = False
        for category in ['pins', 'others']:
            if category in config and key in config[category]:
                config[category][key] = val
                found = True
                break
        if not found:
            if 'others' not in config: config['others'] = {}
            config['others'][key] = val

    with open(output_path, 'w') as f:
        f.write("// Auto-generated by defineparse.py from config.yaml. DO NOT EDIT.\n")
        f.write("#ifndef APP_CONFIG_H\n")
        f.write("#define APP_CONFIG_H\n\n")

        f.write("// Pin Definitions\n")
        pins = config.get('pins', {})
        for name, value in pins.items():
            f.write(f"#define {name} {value}\n")
        
        f.write("\n// Feature Flags & Others\n")
        others = config.get('others', {})
        for name, value in others.items():
            if name == "TABLE_ANGLES":
                if value == "unbounded":
                    f.write("#define TABLE_UNBOUNDED true\n")
                else:
                    f.write("#define TABLE_UNBOUNDED false\n")
            elif isinstance(value, bool):
                if value:
                    f.write(f"#define {name}\n")
                else:
                    f.write(f"// #define {name}\n")
            elif isinstance(value, str):
                f.write(f"#define {name} \"{value}\"\n")
            else:
                f.write(f"#define {name} {value}\n")

        f.write("\n#endif\n")
    print(f"Generated {output_path} with {len(overrides)} overrides.")

if __name__ == "__main__":
    # If running manually: python defineparse.py config.yaml include/AppConfig.h KEY1=VAL1 KEY2=VAL2
    if len(sys.argv) < 3:
        project_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        c_path = os.path.join(project_root, "config.yaml")
        o_path = os.path.join(project_root, "include", "AppConfig.h")
        args = sys.argv[1:]
    else:
        c_path = sys.argv[1]
        o_path = sys.argv[2]
        args = sys.argv[3:]

    overrides = {}
    for arg in args:
        if '=' in arg:
            k, v = arg.split('=', 1)
            overrides[k] = parse_value(v)

    generate_config(c_path, o_path, overrides)
